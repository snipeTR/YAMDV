#!/usr/bin/env python3
"""Generates crates/yamdv-core/src/html_entities.rs (BUG-04) from the WHATWG entities.json.

Usage: python3 tools/gen_entities.py entities.json   (download it once from
https://html.spec.whatwg.org/entities.json; the product never touches the network).
Format: a packed (name, value) table (tools/pack_table.py) sorted by name bytes (binary search, F-39); `name`
keeps its `;` when the reference needs one (the legacy forms without `;` are separate entries)."""
import json, sys

d = json.load(open(sys.argv[1], encoding="utf-8"))
recs = sorted(((k[1:], v["characters"]) for k, v in d.items()), key=lambda r: r[0].encode())
sys.path.insert(0, __import__("os").path.dirname(__file__))
from pack_table import pack
src = f'''// SPDX-License-Identifier: AGPL-3.0-or-later
//! The full HTML5 named character reference table (BUG-04): {len(recs)} names.
//! Generated by `tools/gen_entities.py` from the WHATWG `entities.json`; do not edit.

/// (name, value), sorted by name bytes for binary search (F-39: static data, nothing is built
/// at run time). `name` keeps its `;` when the reference needs one; the legacy forms without
/// `;` are separate entries.
''' + pack("ENTITIES", recs)
open("crates/yamdv-core/src/html_entities.rs", "w", encoding="utf-8").write(src)
print(len(recs))
